  const supported=['en','ja','zh','ko','es','fr','vi','pt'];
  const catalogs=new Map();
  const pending=new Map();
  const records=[];
  const attributeRecords=[];
  let captured=false;
  const language=()=>root.document?.documentElement.lang||'en';
  function catalog(lang=language()){return catalogs.get(lang);}
  function text(key,vars={},lang=language()){
    const value=catalog(lang)?.ui?.[key]??english[key]??key;
    return value.replace(/\{(\w+)\}/g,(match,name)=>vars[name]===undefined?match:String(vars[name]));
  }
  async function load(lang){
    if(!supported.includes(lang))throw new Error('Unsupported language');
    if(catalogs.has(lang))return;
    if(!pending.has(lang))pending.set(lang,fetch(`i18n/${lang}.json?v=20261114-plan2`,{cache:'no-cache'}).then(async response=>{
      if(!response.ok)throw new Error('Translation catalog unavailable');
      const data=await response.json();
      if(data.language!==lang)throw new Error('Translation catalog mismatch');
      catalogs.set(lang,data);
    }).finally(()=>pending.delete(lang)));
    return pending.get(lang);
  }
  function place(name,lang=language()){return catalog(lang)?.places?.[name]||name;}
  function details(it,lang=language()){
    const data=catalog(lang);
    if(!data)return it;
    const days=data.days[String(it.id)];
    return {...it,price:it.price==='Custom quote'?text('customQuote',{},lang):it.price,highlights:it.highlights.map(item=>data.highlights[item]||place(item,lang)),days:it.days.map((day,i)=>({...day,t:days?.[i]?.[0]||day.t,d:days?.[i]?.[1]||day.d}))};
  }
  function signals(source,id,lang=language()){
    const copy=catalog(lang)?.signals?.[String(id)];
    return {...source,seasonKey:source.bestTime,...(copy?{bestTime:copy[0],practical:copy[1]}:{})};
  }
  function site(source,lang=language()){
    const copy=catalog(lang)?.sites?.[source.id];
    if(!copy)return source;
    const [name,subtitle,region,experience,pace,desc,tip]=copy;
    return {...source,name,subtitle,region,experience,pace,desc,tip};
  }
  function capture(){
    if(captured||!root.document)return;
    captured=true;
    const reverse=new Map(Object.entries(english).map(([key,value])=>[value,key]));
    const walker=document.createTreeWalker(document.body,NodeFilter.SHOW_TEXT);
    let node;
    while((node=walker.nextNode())){
      if(node.parentElement?.closest('script,style,noscript,#chatMsgs'))continue;
      const key=reverse.get(node.nodeValue.trim());
      if(key)records.push({node,key,leading:node.nodeValue.match(/^\s*/)[0],trailing:node.nodeValue.match(/\s*$/)[0]});
    }
    document.querySelectorAll('[aria-label],[title],[alt],[placeholder]').forEach(element=>{
      for(const name of ['aria-label','title','alt','placeholder']){
        const key=reverse.get(element.getAttribute(name));
        if(key)attributeRecords.push({element,name,key});
      }
    });
  }
  function apply(lang){
    for(const item of records)if(item.node.isConnected)item.node.nodeValue=item.leading+text(item.key,{},lang)+item.trailing;
    for(const item of attributeRecords)if(item.element.isConnected)item.element.setAttribute(item.name,text(item.key,{},lang));
  }
  const api={english,supported,load,text,place,details,signals,site,catalog,capture,apply};
